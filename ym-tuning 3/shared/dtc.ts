export type DtcKind = 'generic' | 'manufacturer';

export function dtcKind(code: string): DtcKind {
  // Second character: 0 (and P2/P3 partly) generic; 1 manufacturer. We treat only *0xxx as generic.
  return /^[PCBU]0/.test(code) || /^P2/.test(code) ? 'generic' : 'manufacturer';
}

export function describeDtc(code: string): string | undefined {
  return DTC_HE[code];
}
